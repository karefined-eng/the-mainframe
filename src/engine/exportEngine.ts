import type { BaseItem } from "../App";

export interface ExportableCard {
  id?: number;
  title: string;
  draft_content?: string | null;
  order_index?: number;
}

export function exportCardAsOriginMd(item: BaseItem, cards: ExportableCard[] = []): string {
  const sections: string[] = [];

  sections.push(`# Why I Started ${item.title}\n`);
  
  if (item.notes) {
    sections.push(`${item.notes}\n`);
  }

  if (item.raw_import_text) {
    sections.push(`### The Raw Voice Memo (Verbatim Transcript)\n`);
    sections.push(`> "${item.raw_import_text.trim()}"\n`);
  }

  if (cards.length > 0) {
    for (const card of cards) {
      sections.push(`## ${card.title}\n`);
      if (card.draft_content) {
        sections.push(`${card.draft_content.trim()}\n`);
      }
    }
  }

  sections.push(`---\n*Generated by The Mainframe — Sovereign Life & Project OS*`);
  return sections.join("\n");
}

export function exportCardAsMarkdown(item: BaseItem, cards: ExportableCard[] = []): string {
  const sections: string[] = [];

  sections.push(`# ${item.title}\n`);
  sections.push(`- **Status:** ${item.status}`);
  if (item.target_date) {
    sections.push(`- **Target Date:** ${item.target_date}`);
  }
  if (item.target_time) {
    sections.push(`- **Target Time:** ${item.target_time}`);
  }
  sections.push(`- **Created:** ${item.created_at}`);
  sections.push(`- **Last Updated:** ${item.updated_at}\n`);

  if (item.notes) {
    sections.push(`## Summary / Overview\n\n${item.notes}\n`);
  }

  if (item.raw_import_text) {
    sections.push(`## Raw Voice / Ingest Transcript\n\n> ${item.raw_import_text.trim()}\n`);
  }

  if (cards.length > 0) {
    sections.push(`## Cards\n`);
    for (const card of cards) {
      sections.push(`### ${card.title}\n`);
      if (card.draft_content) {
        sections.push(`${card.draft_content.trim()}\n`);
      }
    }
  }

  return sections.join("\n");
}

export function exportCardAsText(item: BaseItem, cards: ExportableCard[] = []): string {
  const lines: string[] = [];

  lines.push(`TITLE: ${item.title}`);
  lines.push(`STATUS: ${item.status}`);
  if (item.target_date) lines.push(`TARGET DATE: ${item.target_date}`);
  if (item.target_time) lines.push(`TARGET TIME: ${item.target_time}`);
  lines.push(`CREATED: ${item.created_at}`);
  lines.push(`UPDATED: ${item.updated_at}`);
  lines.push("");

  if (item.notes) {
    lines.push(`NOTES:\n${item.notes}\n`);
  }

  if (item.raw_import_text) {
    lines.push(`RAW TRANSCRIPT:\n${item.raw_import_text}\n`);
  }

  if (cards.length > 0) {
    lines.push("CARDS:");
    for (const card of cards) {
      lines.push(`- ${card.title.toUpperCase()}:`);
      if (card.draft_content) {
        lines.push(`  ${card.draft_content.trim()}`);
      }
      lines.push("");
    }
  }

  return lines.join("\n");
}

export function downloadFile(filename: string, content: string, mimeType = "text/markdown"): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
